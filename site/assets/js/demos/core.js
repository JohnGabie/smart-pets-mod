  /* ---------- i18n helper ---------- */
  function t(key, fb, vars) {
    var s = (root.SP && typeof root.SP.t === "function") ? root.SP.t(key, fb) : (fb != null ? fb : key);
    if (vars) s = String(s).replace(/\{(\w+)\}/g, function (m, n) { return vars[n] != null ? vars[n] : m; });
    return s;
  }

  /* ---------- DOM helper ---------- */
  function h(tag, attrs, kids) {
    var el = document.createElement(tag), k;
    attrs = attrs || {};
    for (k in attrs) {
      if (!Object.prototype.hasOwnProperty.call(attrs, k)) continue;
      var v = attrs[k];
      if (v == null || v === false) continue;
      if (k === "class") el.className = v;
      else if (k === "text") el.textContent = v;
      else if (k.slice(0, 2) === "on" && typeof v === "function") el.addEventListener(k.slice(2), v);
      else if (v === true) el.setAttribute(k, "");
      else el.setAttribute(k, v);
    }
    (kids || []).forEach(function (c) { if (c != null) el.appendChild(typeof c === "string" ? document.createTextNode(c) : c); });
    return el;
  }

  /* ---------- registry / mount ---------- */
  var registry = {}, pending = [], ctxs = [], uid = 0;

  function reducedMotion() {
    try { return !!(root.matchMedia && root.matchMedia("(prefers-reduced-motion: reduce)").matches); } catch (e) { return false; }
  }

  function makeCtx(el, name) {
    var ctx = { el: el, name: name, id: "spd" + (++uid), t: t, h: h, disposed: false };
    var bindings = [], langFns = [], disposers = [], connected = false;
    ctx.reduced = reducedMotion;
    ctx.bind = function (node, fn, attr) {
      var b = { node: node, fn: fn, attr: attr };
      function upd() { var s = fn(); if (attr) node.setAttribute(attr, s); else node.textContent = s; }
      b.upd = upd; bindings.push(b); upd(); return upd;
    };
    ctx.tx = function (node, key, fb, attr) { return ctx.bind(node, function () { return t(key, fb); }, attr); };
    ctx.onLang = function (fn) { langFns.push(fn); };
    ctx.relang = function () {
      bindings.forEach(function (b) { b.upd(); });
      langFns.forEach(function (fn) { try { fn(); } catch (e) { console.error(e); } });
    };
    ctx.cleanup = function (fn) { disposers.push(fn); };
    ctx.loop = function (fn, fps) {
      var raf = 0, last = null, acc = 0, frame = 0, visible = true, io = null, step = 1 / (fps || 10);
      if (typeof root.IntersectionObserver === "function") {
        io = new root.IntersectionObserver(function (es) { visible = es[es.length - 1].isIntersecting; });
        io.observe(el);
      }
      function tick(ts) {
        if (ctx.disposed) return;
        raf = root.requestAnimationFrame(tick);
        if (!el.isConnected) { if (connected) ctx.dispose(); return; }
        connected = true;
        if (last == null) last = ts;
        var dt = (ts - last) / 1000; last = ts;
        if (!visible || document.hidden) return;
        acc += Math.min(dt, 0.25);
        if (acc < step) return;
        var d = acc; acc = 0; frame++;
        try { fn(d, frame); } catch (e) { console.error(e); }
      }
      raf = root.requestAnimationFrame(tick);
      disposers.push(function () { root.cancelAnimationFrame(raf); if (io) io.disconnect(); });
    };
    /* integer-scaled canvas: internal size w x h, CSS size = w*m x h*m, m = floor(available/w) */
    ctx.fit = function (canvas, w, hh, maxMul) {
      canvas.width = w; canvas.height = hh;
      function size() {
        var host = (canvas.closest && canvas.closest(".spd-main")) || el, avail = host.clientWidth ? host.clientWidth - 12 : w;
        var m = Math.max(1, Math.min(maxMul || 6, Math.floor(avail / w)));
        canvas.style.width = (w * m) + "px"; canvas.style.height = (hh * m) + "px";
      }
      size();
      if (typeof root.ResizeObserver === "function") {
        var ro = new root.ResizeObserver(size); ro.observe(el); disposers.push(function () { ro.disconnect(); });
      } else { root.addEventListener("resize", size); disposers.push(function () { root.removeEventListener("resize", size); }); }
      return canvas.getContext("2d");
    };
    ctx.dispose = function () {
      if (ctx.disposed) return; ctx.disposed = true;
      disposers.forEach(function (d) { try { d(); } catch (e) {} });
      var i = ctxs.indexOf(ctx); if (i >= 0) ctxs.splice(i, 1);
    };
    return ctx;
  }

  function mount(name, el) {
    if (!el) return;
    if (el.__spd) { el.__spd.dispose(); el.__spd = null; }
    var fn = registry[name];
    if (!fn) { pending.push([name, el]); return; }
    while (el.firstChild) el.removeChild(el.firstChild);
    el.classList.add("spd-root");
    el.setAttribute("data-demo-ready", name);
    var ctx = makeCtx(el, name);
    el.__spd = ctx; ctxs.push(ctx);
    try { fn(el, ctx); }
    catch (e) {
      console.error("SPDemos: failed to mount " + name, e);
      el.appendChild(h("p", { class: "spd-error", role: "alert", text: t("demos.error", "This demo could not start.") }));
    }
    return ctx;
  }
  function register(name, fn) {
    registry[name] = fn;
    var rest = [];
    pending.forEach(function (p) { if (p[0] === name) mount(p[0], p[1]); else rest.push(p); });
    pending = rest;
  }
  function autoMount() {
    var nodes = document.querySelectorAll("[data-demo]");
    for (var i = 0; i < nodes.length; i++) {
      var n = nodes[i], nm = n.getAttribute("data-demo");
      if (!n.__spd && registry[nm]) mount(nm, n);
    }
  }

