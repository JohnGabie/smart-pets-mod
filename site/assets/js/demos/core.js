      gray:  { main: "#8a8f98", shade: "#686d76", light: "#b4b8bf", patch: "#4b4f57" },
      red:   { main: "#d9902f", shade: "#b06e1d", light: "#f0c06a", patch: "#8e4a14" },
      brown: { main: "#7a4a2b", shade: "#5a3319", light: "#a2714a", patch: "#2f1a0e" },
