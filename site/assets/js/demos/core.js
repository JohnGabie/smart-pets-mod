    header: function (ctx, title, blurb) {
      var badge = h("span", { class: "mc-badge mc-badge--research spd-label" });
      ctx.tx(badge, "demos.label", "Concept demo, not real gameplay");
      var tt = h("h3", { class: "spd-title" }); ctx.tx(tt, title[0], title[1]);
      var p = h("p", { class: "spd-blurb" }); ctx.tx(p, blurb[0], blurb[1]);
      return h("div", { class: "spd-head" }, [h("div", { class: "spd-head-row" }, [tt, badge]), p]);
    },
    button: function (ctx, label, onclick, cls) {
      var b = h("button", { type: "button", class: "mc-btn spd-btn" + (cls ? " " + cls : ""), onclick: onclick });
      ctx.tx(b, label[0], label[1]);
      return b;
    },
    status: function (ctx) {
      var el = h("p", { class: "spd-status", role: "status", "aria-live": "polite" });
      var cur = null;
      var upd = ctx.bind(el, function () { return cur ? t(cur[0], cur[1], cur[2]) : ""; });
      return { el: el, set: function (key, fb, vars) { cur = [key, fb, vars]; upd(); } };
    },
    select: function (ctx, id, options, value, onchange) {
      var s = h("select", { class: "spd-select", id: id, onchange: function () { onchange(s.value); } });
      options.forEach(function (o) {
        var op = h("option", { value: o.value }); ctx.tx(op, o.label[0], o.label[1]); s.appendChild(op);
      });
      s.value = value; return s;
    },
    field: function (ctx, id, label, control) {
      var l = h("label", { class: "spd-field-label", for: id }); ctx.tx(l, label[0], label[1]);
      return h("div", { class: "spd-field" }, [l, control]);
    },
    log: function (ctx, max) {
      var el = h("ol", { class: "spd-log mc-code", role: "log", "aria-live": "polite", "aria-label": t("demos.log.aria", "Event log") });
      ctx.bind(el, function () { return t("demos.log.aria", "Event log"); }, "aria-label");
      var entries = [];
      function render() {
        while (el.firstChild) el.removeChild(el.firstChild);
        entries.forEach(function (e) {
          var li = h("li", { class: "spd-log-" + e.kind });
          if (e.tag) li.appendChild(h("span", { class: "spd-log-tag", text: e.tag }));
          if (e.msg) li.appendChild(h("span", { class: "spd-log-msg", text: " " + t(e.msg[0], e.msg[1], e.msg[2]) }));
          el.appendChild(li);
        });
      }
      ctx.onLang(render);
      return {
        el: el,
        add: function (kind, tag, msg) { entries.push({ kind: kind, tag: tag, msg: msg }); if (entries.length > (max || 12)) entries.shift(); render(); el.scrollTop = el.scrollHeight; },
        clear: function () { entries = []; render(); }
      };
    },
    meter: function (cls) {
      var bar = h("span"); var box = h("div", { class: "mc-xp spd-meter " + (cls || "") }, [bar]);
      return { el: box, bar: bar, set: function (pct) { bar.style.width = Math.max(0, Math.min(100, pct)) + "%"; } };
    }
